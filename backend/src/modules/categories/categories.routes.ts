import { Router } from "express";
import { protect, requirePermission } from "../../middleware/auth.middleware";
import { upload } from "../../middleware/upload.middleware";
import * as C from "./categories.controller";
const router = Router();
router.use(protect);
router.get("/", requirePermission("categories.view", "categories.manage"), C.list);
router.post("/", requirePermission("categories.manage"), C.create);
router.get("/export", requirePermission("categories.view", "categories.manage"), C.exportSpreadsheet);
router.post("/import/preview", requirePermission("categories.manage"), upload.single("file"), C.previewImport);
router.post("/import", requirePermission("categories.manage"), upload.single("file"), C.importSpreadsheet);
router.put("/reorder", requirePermission("categories.manage"), C.reorder);
router.post("/bulk/permanent", requirePermission("categories.manage"), C.bulkPermanentDelete);
router.get("/:id/countries", requirePermission("categories.view", "categories.manage"), C.listCountries);
router.put("/:id/countries", requirePermission("categories.manage"), C.updateCountries);
router.get("/:id", requirePermission("categories.view", "categories.manage"), C.getOne);
router.put("/:id", requirePermission("categories.manage"), C.update);
router.post("/:id/duplicate", requirePermission("categories.manage"), C.duplicate);
router.post("/:id/archive", requirePermission("categories.manage"), C.archive);
router.post("/:id/restore", requirePermission("categories.manage"), C.restore);
router.delete("/:id/permanent", requirePermission("categories.manage"), C.permanentDelete);
router.delete("/:id", requirePermission("categories.manage"), C.remove);
export default router;
