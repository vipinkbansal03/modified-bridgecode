import { Router } from "express";
import { protect, requirePermission } from "../../middleware/auth.middleware";
import * as C from "./categories.controller";
const router = Router();
router.use(protect);
router.get("/", requirePermission("categories.view", "categories.manage"), C.list);
router.post("/", requirePermission("categories.manage"), C.create);
router.put("/reorder", requirePermission("categories.manage"), C.reorder);
router.get("/:id/countries", requirePermission("categories.view", "categories.manage"), C.listCountries);
router.put("/:id/countries", requirePermission("categories.manage"), C.updateCountries);
router.get("/:id", requirePermission("categories.view", "categories.manage"), C.getOne);
router.put("/:id", requirePermission("categories.manage"), C.update);
router.delete("/:id", requirePermission("categories.manage"), C.remove);
export default router;
